def apply_replacements(text: str, name: str) -> tuple[str, list[str]]:
    """应用稳定替换表，返回新文本与命中记录。"""
    hits: list[str] = []
    for old, new in REPLACEMENTS:
        if old in text:
            text = text.replace(old, new)
            hits.append(f"{old} → {new}")
    for old, new in FILE_SPECIFIC.get(name, []):
        if old in text:
            text = text.replace(old, new)
            hits.append(f"[file] {old} → {new}")
    if BARE_AI.search(text):
        text = BARE_AI.sub("海洋", text)
        text = text.replace("海洋 内容", "海洋内容").replace("海洋 相关", "海洋相关")
        hits.append("裸 AI → 海洋")
    return text, hits


def build(upstream: Path, out: Path) -> int:
    prompts_src = upstream / "prompts"
    if not prompts_src.is_dir():
        print(f"找不到上游提示词目录: {prompts_src}", file=sys.stderr)
        return 2
    out.mkdir(parents=True, exist_ok=True)
    prompts_out = out / "prompts"
    prompts_out.mkdir(exist_ok=True)

    report: list[str] = ["# 海洋包改动说明", "",
                         "由 `tools/build_ocean_pack.py` 生成。人工整份改写的文件标 **重写**，其余为结构保持的行业替换。", ""]

    # 读取 taxonomy 里的标签，供 content-understanding 的占位符填入
    tax = (out / "taxonomy.ts").read_text(encoding="utf-8") if (out / "taxonomy.ts").exists() else ""
    cat_tags = re.findall(r'^\s*"([^"]+)",\s*$', tax.split("export const CATEGORY_TAGS")[1].split("] as const")[0], re.M) if "CATEGORY_TAGS" in tax else []
    topic_tags = re.findall(r'"([^"]+)"', tax.split("export const TOPIC_TAGS")[1].split("] as const")[0]) if "TOPIC_TAGS" in tax else []
    entity_tags = re.findall(r'"([^"]+)"', tax.split("export const ENTITY_TAGS")[1].split("] as const")[0]) if "ENTITY_TAGS" in tax else []
    fills = {
        "{category_tags}": "、".join(cat_tags) if cat_tags else "论文/研究、数据/产品更新、政策/法规",
        "{topic_tags}": "、".join(topic_tags) if topic_tags else "海温、环流",
        "{entity_tags}": "、".join(entity_tags) if entity_tags else "NOAA、IOC-UNESCO",
    }

    for src in sorted(prompts_src.glob("*.md")):
        name = src.name
        original = src.read_text(encoding="utf-8")
        if name in HANDWRITTEN_FILES:
            text = HANDWRITTEN_FILES[name]
            for k, v in fills.items():
                text = text.replace(k, v)
            report.append(f"- `prompts/{name}` — **重写**（行业判断整份替换，结构与输出契约不变）")
        else:
            text, hits = apply_replacements(original, name)
            if hits:
                report.append(f"- `prompts/{name}` — 行业替换 {len(hits)} 处：" + "；".join(hits[:6]) + ("……" if len(hits) > 6 else ""))
            else:
                report.append(f"- `prompts/{name}` — 原样保留（不含行业词）")
        (prompts_out / name).write_text(text, encoding="utf-8", newline="\n")

    (out / "REPORT.md").write_text("\n".join(report) + "\n", encoding="utf-8", newline="\n")
    print(f"提示词已生成：{len(list(prompts_out.glob('*.md')))} 份 → {prompts_out}")
    return 0


def check(out: Path) -> int:
    prompts = out / "prompts"
    bad = 0
    for f in sorted(prompts.glob("*.md")):
        text = f.read_text(encoding="utf-8")
        found = [w for w in RESIDUE if w in text]
        if found:
            bad += 1
            print(f"残留 {f.name}: {', '.join(found)}")
    # 契约检查：占位符与 JSON 输出字段必须还在
    must = {
        "prefilter.md": ['"label"', "PASS", "BLOCK", "UNKNOWN"],
        "selection-score.md": ["attentionScore", "sig", "nov", "cred", "reson", "act"],
        "structure.md": ["category", "tags", "subjects", "scope", "fact", "{{categoryGuide}}", "{{entities}}"],
        "content-understanding.md": ["titleZh", "summaryZh", "editorialJudgment", "itemType", "authorRole"],
        "story-digest.md": ['"title"', '"digest"'],
        "group-batch.md": ["SAME_OCCURRENCE", "SAME_STORY", "UNRELATED", "ROUNDUP", "addsValue"],
    }
    for name, tokens in must.items():
        f = prompts / name
        if not f.exists():
            print(f"缺文件: {name}")
            bad += 1
            continue
        text = f.read_text(encoding="utf-8")
        missing = [t for t in tokens if t not in text]
        if missing:
            print(f"契约缺失 {name}: {missing}")
            bad += 1
    print("契约与残留检查通过。" if bad == 0 else f"检查未通过：{bad} 项")
    return 0 if bad == 0 else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="生成海洋行业包")
    ap.add_argument("--upstream", type=Path, default=ROOT / "_ref" / "AIHOT-main" / "industry")
    ap.add_argument("--out", type=Path, default=ROOT / "ocean-pack" / "industry")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if args.check:
        return check(args.out)
    code = build(args.upstream, args.out)
    if code == 0:
        code = check(args.out)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
